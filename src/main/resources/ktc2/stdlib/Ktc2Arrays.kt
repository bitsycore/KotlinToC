private fun checkRange(fromIndex: Int, toIndex: Int, size: Int) {
	if (fromIndex < 0 || toIndex > size) throw IndexOutOfBoundsException("fromIndex: $fromIndex, toIndex: $toIndex, size: $size")
	if (fromIndex > toIndex) throw IllegalArgumentException("fromIndex: $fromIndex > toIndex: $toIndex")
}

private fun checkCopy(startIndex: Int, endIndex: Int, size: Int, destinationOffset: Int, destinationSize: Int) {
	if (startIndex < 0 || endIndex > size || startIndex > endIndex) {
		throw IndexOutOfBoundsException("startIndex: $startIndex, endIndex: $endIndex, size: $size")
	}
	if (destinationOffset < 0 || destinationOffset + (endIndex - startIndex) > destinationSize) {
		throw IndexOutOfBoundsException("destinationOffset: $destinationOffset, count: ${endIndex - startIndex}, destination size: $destinationSize")
	}
}

