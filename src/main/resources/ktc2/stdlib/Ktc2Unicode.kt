/** The number written as four hexadecimal digits at [inAt] of [inText]. */
private fun hexAt(inText: String, inAt: Int): Int {
	var vValue = 0
	for (vIndex in inAt until inAt + 4) {
		val vDigit = inText[vIndex].code
		vValue = vValue * 16 + if (vDigit <= '9'.code) vDigit - '0'.code else vDigit - 'A'.code + 10
	}
	return vValue
}

/** The numbers of [inText], four digits each. */
private fun decoded(inText: String): CharArray = CharArray(inText.length / 4) { hexAt(inText, it * 4).toChar() }

/** The numbers at the even places of [inPairs] (`inOffset` 0) or at the odd ones (1). */
private fun half(inPairs: CharArray, inOffset: Int): CharArray = CharArray(inPairs.size / 2) { inPairs[it * 2 + inOffset] }

private val gCategoryStarts: CharArray = CharArray(kCategoryRuns.length / 5) { hexAt(kCategoryRuns, it * 5).toChar() }
private val gCategories: ByteArray = ByteArray(kCategoryRuns.length / 5) { (kCategoryRuns[it * 5 + 4].code - 'a'.code).toByte() }
private val gUpperCaseRanges: CharArray = decoded(kUpperCaseRanges)
private val gLowerCaseRanges: CharArray = decoded(kLowerCaseRanges)
private val gWhitespaceRanges: CharArray = decoded(kWhitespaceRanges)
private val gToUpperPairs: CharArray = decoded(kToUpperCase)
private val gToLowerPairs: CharArray = decoded(kToLowerCase)
private val gToTitlePairs: CharArray = decoded(kToTitleCase)
private val gUpperFrom: CharArray = half(gToUpperPairs, 0)
private val gUpperTo: CharArray = half(gToUpperPairs, 1)
private val gLowerFrom: CharArray = half(gToLowerPairs, 0)
private val gLowerTo: CharArray = half(gToLowerPairs, 1)
private val gTitleFrom: CharArray = half(gToTitlePairs, 0)
private val gTitleTo: CharArray = half(gToTitlePairs, 1)
private val gDigitZeros: CharArray = decoded(kDigitZeros)

