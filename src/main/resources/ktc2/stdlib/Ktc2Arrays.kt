/** [inElement] as text, an array inside an array being written out like the outer one. */
private fun deepToString(inElement: Any?): String = when (arrayKind(inElement)) {
	1 -> (inElement as Array<*>).contentDeepToString()
	2 -> (inElement as BooleanArray).contentToString()
	3 -> (inElement as ByteArray).contentToString()
	4 -> (inElement as ShortArray).contentToString()
	5 -> (inElement as IntArray).contentToString()
	6 -> (inElement as LongArray).contentToString()
	7 -> (inElement as CharArray).contentToString()
	8 -> (inElement as FloatArray).contentToString()
	9 -> (inElement as DoubleArray).contentToString()
	else -> inElement.toString()
}

