private fun deepEquals(inLeft: Any?, inRight: Any?): Boolean {
	val vKind = arrayKind(inLeft)
	if (vKind != arrayKind(inRight)) return false
	return when (vKind) {
		1 -> (inLeft as Array<*>).contentDeepEquals(inRight as Array<*>)
		2 -> (inLeft as BooleanArray).contentEquals(inRight as BooleanArray)
		3 -> (inLeft as ByteArray).contentEquals(inRight as ByteArray)
		4 -> (inLeft as ShortArray).contentEquals(inRight as ShortArray)
		5 -> (inLeft as IntArray).contentEquals(inRight as IntArray)
		6 -> (inLeft as LongArray).contentEquals(inRight as LongArray)
		7 -> (inLeft as CharArray).contentEquals(inRight as CharArray)
		8 -> (inLeft as FloatArray).contentEquals(inRight as FloatArray)
		9 -> (inLeft as DoubleArray).contentEquals(inRight as DoubleArray)
		else -> inLeft == inRight
	}
}

