	for (vIndex in inAt until inAt + 2) {
		val vDigit = inText[vIndex].code
		vValue = vValue * 16 + if (vDigit <= '9'.code) vDigit - '0'.code else vDigit - 'A'.code + 10
	}
	return vValue
}

private val gScriptStarts: CharArray = CharArray(kScriptRuns.length / 6) { hexAt(kScriptRuns, it * 6).toChar() }
private val gScripts: IntArray = IntArray(kScriptRuns.length / 6) { hexByteAt(kScriptRuns, it * 6 + 4) }
private val gBlockStarts: CharArray = CharArray(kBlockRuns.length / 6) { hexAt(kBlockRuns, it * 6).toChar() }
private val gBlocks: IntArray = IntArray(kBlockRuns.length / 6) { hexByteAt(kBlockRuns, it * 6 + 4) }

/** The place of the script of [inChar] among the names of scripts. */
internal fun unicodeScript(inChar: Char): Int = gScripts[floorIndex(gScriptStarts, inChar)]

/** The place of the block of [inChar] among the names of blocks; 255 when it is in none. */
internal fun unicodeBlock(inChar: Char): Int = gBlocks[floorIndex(gBlockStarts, inChar)]

/** [inName] in capitals and without what separates its words, which is how names are compared. */
private fun plainName(inName: String): String {
	val vText = StringBuilder(inName.length)
	for (vChar in inName) if (vChar != ' ' && vChar != '_' && vChar != '-') vText.append(vChar.uppercaseChar())
	return vText.toString()
}

/** The place of [inName] in [inNames], a list of names each followed by a comma; -1 when it is not there. */
private fun placeOfName(inNames: String, inName: String): Int {
	val vWanted = plainName(inName)
	var vStart = 0
	var vPlace = 0
	while (vStart < inNames.length) {
		val vEnd = inNames.indexOf(',', vStart)
		if (plainName(inNames.substring(vStart, vEnd)) == vWanted) return vPlace
		vStart = vEnd + 1
		vPlace++
	}
	return -1
}

/** The place of the script called [inName] (`Latin`, `OLD_ITALIC`), or -1. */
internal fun unicodeScriptNamed(inName: String): Int = placeOfName(kScriptNames, inName)

/** The place of the block called [inName] (`Greek`, `BasicLatin`, `Basic Latin`), or -1. */
internal fun unicodeBlockNamed(inName: String): Int = placeOfName(kBlockNames, inName)

