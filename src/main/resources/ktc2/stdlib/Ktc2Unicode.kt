/** The place in the sorted [inSorted] of the last element not above [inChar]; -1 when all are above. */
private fun floorIndex(inSorted: CharArray, inChar: Char): Int {
	var vLow = 0
	var vHigh = inSorted.size - 1
	while (vLow <= vHigh) {
		val vMiddle = (vLow + vHigh) ushr 1
		if (inSorted[vMiddle] <= inChar) vLow = vMiddle + 1 else vHigh = vMiddle - 1
	}
	return vHigh
}

/** True when [inChar] is in one of [inRanges], which holds the first and the last character of each. */
private fun inRanges(inRanges: CharArray, inChar: Char): Boolean {
	val vAt = floorIndex(inRanges, inChar)
	// An even place is the start of a range; an odd one its end, which is in only when it is the character itself.
	return vAt >= 0 && (vAt % 2 == 0 || inRanges[vAt] == inChar)
}

/** What [inFrom] maps [inChar] to in [inTo]; the character itself when it is not there. */
private fun mapped(inFrom: CharArray, inTo: CharArray, inChar: Char): Char {
	val vAt = floorIndex(inFrom, inChar)
	return if (vAt >= 0 && inFrom[vAt] == inChar) inTo[vAt] else inChar
}

/** The ordinal of the CharCategory of [inChar]. */
internal fun unicodeCategory(inChar: Char): Int = gCategories[floorIndex(gCategoryStarts, inChar)].toInt()

internal fun unicodeIsUpperCase(inChar: Char): Boolean = inRanges(gUpperCaseRanges, inChar)

internal fun unicodeIsLowerCase(inChar: Char): Boolean = inRanges(gLowerCaseRanges, inChar)

internal fun unicodeIsWhitespace(inChar: Char): Boolean = inRanges(gWhitespaceRanges, inChar)

internal fun unicodeToUpperCase(inChar: Char): Char = mapped(gUpperFrom, gUpperTo, inChar)

internal fun unicodeToLowerCase(inChar: Char): Char = mapped(gLowerFrom, gLowerTo, inChar)

/** The titlecase form: the uppercase one except for the few characters that have their own. */
internal fun unicodeToTitleCase(inChar: Char): Char {
	val vAt = floorIndex(gTitleFrom, inChar)
	return if (vAt >= 0 && gTitleFrom[vAt] == inChar) gTitleTo[vAt] else unicodeToUpperCase(inChar)
}

/**
 * The uppercase form of [inChar] in a string when it is not its single-character mapping
 * (`ß` gives `SS`); null for every other character.
 */
internal fun unicodeUpperCaseString(inChar: Char): String? {
	if (inChar.code < 0xB5) return null
	var vAt = 0
	while (vAt < kUpperCaseStrings.length) {
		val vCount = kUpperCaseStrings[vAt + 4].code - '0'.code
		val vCode = hexAt(kUpperCaseStrings, vAt)
		if (vCode == inChar.code) {
			val vText = StringBuilder(vCount)
			for (vIndex in 0 until vCount) vText.append(hexAt(kUpperCaseStrings, vAt + 5 + vIndex * 4).toChar())
			return vText.toString()
		}
		// The table is in the order of the characters.
		if (vCode > inChar.code) return null
		vAt += 5 + vCount * 4
	}
	return null
}

/** The value of [inChar] as a decimal digit of any script; -1 when it is not one. */
internal fun unicodeDigit(inChar: Char): Int {
	val vAt = floorIndex(gDigitZeros, inChar)
	if (vAt < 0) return -1
	val vValue = inChar.code - gDigitZeros[vAt].code
	return if (vValue <= 9) vValue else -1
}

