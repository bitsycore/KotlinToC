package com.bitsycore.ktc2.interop

import java.io.File
import java.util.concurrent.TimeUnit

// ==================
// MARK: .def file
// ==================

/**
 * A Kotlin/Native interop definition file: `key = value` lines, then optionally a line `---`
 * followed by C code that is part of the library as seen from Kotlin.
 *
 * Understood keys: `headers`, `package`, `headerFilter`, `compilerOpts`, `linkerOpts`, and the
 * last two with a platform suffix (`.mingw`, `.linux`, `.osx`).
 */
class DefFile(val file: File) {
	val headers: List<String>
	val headerFilter: List<String>
	val packageName: String
	val compilerOpts: List<String>
	val linkerOpts: List<String>
	val inlineC: String

	init {
		val vLines = file.readLines()
		val vSeparator = vLines.indexOfFirst { it.trim() == "---" }
		val vProperties = HashMap<String, String>()
		for (vLine in if (vSeparator < 0) vLines else vLines.subList(0, vSeparator)) {
			val vText = vLine.trim()
			if (vText.isEmpty() || vText.startsWith("#")) continue
			val vEquals = vText.indexOf('=')
			if (vEquals > 0) vProperties[vText.substring(0, vEquals).trim()] = vText.substring(vEquals + 1).trim()
		}
		val vOs = System.getProperty("os.name").lowercase()
		val vPlatform = if ("win" in vOs) "mingw" else if ("mac" in vOs) "osx" else "linux"
		fun words(inKey: String): List<String> =
			listOfNotNull(vProperties[inKey], vProperties["$inKey.$vPlatform"]).flatMap { it.split(Regex("\\s+")) }.filter { it.isNotEmpty() }
		headers = words("headers")
		headerFilter = words("headerFilter")
		packageName = vProperties["package"] ?: file.nameWithoutExtension
		compilerOpts = words("compilerOpts")
		linkerOpts = words("linkerOpts")
		inlineC = if (vSeparator < 0) "" else vLines.subList(vSeparator + 1, vLines.size).joinToString("\n")
	}
}

// ==================
// MARK: Generator
// ==================

/** What a `.def` file turned into. */
class Bindings(
	/** The generated Kotlin source, to compile with the program. */
	val source: File,
	/** Options the C compiler needs to find the library's headers. */
	val compilerOpts: List<String>,
	val linkerOpts: List<String>,
)

private val kKotlinKeywords = setOf(
	"as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null", "object", "package",
	"return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while",
)

/**
 * Generates Kotlin bindings for the C library a `.def` file describes, the way Kotlin/Native's
 * cinterop does: the headers are preprocessed by the C compiler, their declarations read by
 * [CHeaderParser], and each one written as a Kotlin declaration over `kotlinx.cinterop`.
 *
 * Nothing is wrapped at run time: a bound function is the C call itself, a struct field the C
 * member access, written as `cExpr` text that the back end pastes into the generated C.
 *
 * What is generated:
 * - functions, with `const char*` parameters as `String?` and other pointers as `CValuesRef<T>?`;
 *   variadic functions take `vararg`;
 * - structs and unions as classes with a property per field; a type known only by name is opaque;
 * - enums as an integer `typealias` with a `const val` per constant;
 * - object-like macros with an integer, floating-point or string value as `const val`.
 *
 * - variables declared `extern` as properties.
 *
 * A struct passed or returned by value is a `CValue<T>`.
 *
 * Skipped, with a comment in the generated file: what uses a type Kotlin has no counterpart
 * for (`long double`, `va_list`), or a struct without a name by value.
 */
class BindingGenerator(
	private val mDef: DefFile,
	private val mCompiler: String,
	/** Kotlin declarations added at the end of the generated file. */
	private val mExtraKotlin: String = "",
) {

	private val mOut = StringBuilder()
	private val mDeclared = HashSet<String>()
	private val mClassOf = HashMap<CRecord, String>()
	private val mPendingRecords = ArrayDeque<CRecord>()
	private val mEnumAlias = HashMap<CEnum, String>()

	/**
	 * @param inKotlinDir where the Kotlin file goes
	 * @param inCDir where the generated C is compiled: receives the header that includes the library's
	 */
	fun generate(inKotlinDir: File, inCDir: File): Bindings {
		inKotlinDir.mkdirs()
		inCDir.mkdirs()
		val vStubName = "ktc2_interop_" + mDef.packageName.replace('.', '_') + ".h"
		val vStub = File(inCDir, vStubName)
		val vGuard = vStubName.uppercase().replace('.', '_')
		vStub.writeText(buildString {
			append("/* Generated by ktc2 from ${mDef.file.name}. */\n#ifndef $vGuard\n#define $vGuard\n\n")
			mDef.headers.forEach { append("#include <$it>\n") }
			if (mDef.inlineC.isNotBlank()) append("\n").append(mDef.inlineC).append("\n")
			append("\n#endif\n")
		})
		// Headers next to the .def file are found without an option of their own.
		val vCompilerOpts = mDef.compilerOpts + "-I${mDef.file.absoluteFile.parentFile.invariantSeparatorsPath}"
		// The headers are read as the C the program is compiled as, unless the .def says otherwise.
		val vDialect = if (mDef.compilerOpts.any { it.startsWith("-std=") }) emptyList() else listOf("-std=gnu11")
		val vPredefined = run(listOf(mCompiler, "-dM", "-E", "-x", "c", "-") + vDialect + vCompilerOpts, "")
		val vLongSize = Regex("#define __SIZEOF_LONG__ (\\d+)").find(vPredefined)?.groupValues?.get(1)?.toInt() ?: 8
		val vPreprocessed = run(listOf(mCompiler, "-E", "-dD", "-x", "c") + vDialect + vCompilerOpts + vStub.absolutePath, null)
		val vParser = CHeaderParser(vPreprocessed, vLongSize).parse()

		val vStubPath = vStub.absoluteFile.invariantSeparatorsPath
		val vFilters = (mDef.headers + mDef.headerFilter).map { vGlob ->
			val vPattern = Regex.escape(vGlob.replace('\\', '/')).replace("**", "\u0001").replace("*", "\\E[^/]*\\Q").replace("\u0001", "\\E.*\\Q")
			Regex("(^|.*/)$vPattern$")
		}
		fun isWanted(inFile: String): Boolean {
			val vPath = File(inFile).let { if (it.isAbsolute) it.invariantSeparatorsPath else inFile.replace('\\', '/') }
			return vPath == vStubPath || vPath.endsWith("/$vStubName") || vFilters.any { it.matches(vPath) }
		}

		mOut.append("// Generated by ktc2 from ${mDef.file.name}. Do not edit.\n")
		mOut.append("@file:Suppress(\"unused\", \"UNUSED_PARAMETER\", \"FunctionName\", \"PropertyName\", \"ClassName\", \"SpellCheckingInspection\", \"RedundantVisibilityModifier\", \"REDUNDANT_NULLABLE\", \"UNUSED_TYPEALIAS_PARAMETER\")\n")
		mOut.append("@file:CHeaders(\"\\\"$vStubName\\\"\")\n\n")
		mOut.append("package ${mDef.packageName}\n\n")
		mOut.append("import kotlinx.cinterop.*\nimport kotlinx.cinterop.internal.CHeaders\nimport kotlinx.cinterop.internal.CType\nimport kotlinx.cinterop.internal.CVariadic\nimport kotlinx.cinterop.internal.cExpr\n")

		for (vEnum in vParser.enums.filter { isWanted(it.file) }) enumeration(vEnum)
		for (vRecord in vParser.records.filter { isWanted(it.file) && it.spelling.isNotEmpty() }) classFor(vRecord)
		for (vFunction in vParser.functions.filter { isWanted(it.file) }) function(vFunction)
		// Types the functions mention: bound in full when they are the library's own, by name otherwise.
		while (mPendingRecords.isNotEmpty()) record(mPendingRecords.removeFirst(), ::isWanted)
		for (vVariable in vParser.variables.filter { isWanted(it.file) }) variable(vVariable)
		while (mPendingRecords.isNotEmpty()) record(mPendingRecords.removeFirst(), ::isWanted)
		for (vMacro in vParser.macros.filter { isWanted(it.file) }) macro(vMacro, vParser)

		mOut.append(mExtraKotlin)
		val vSource = File(inKotlinDir, mDef.packageName.replace('.', '_') + ".kt")
		vSource.writeText(mOut.toString())
		return Bindings(vSource, vCompilerOpts, mDef.linkerOpts)
	}

	/** Runs the C compiler and returns what it prints; [inInput] is given on stdin when not null. */
	private fun run(inCommand: List<String>, inInput: String?): String {
		val vErrors = File.createTempFile("ktc2", ".err")
		try {
			val vProcess = ProcessBuilder(inCommand).redirectError(vErrors).start()
			vProcess.outputStream.use { vStream -> inInput?.let { vStream.write(it.toByteArray()) } }
			val vOutput = vProcess.inputStream.readBytes().decodeToString()
			if (!vProcess.waitFor(120, TimeUnit.SECONDS) || vProcess.exitValue() != 0) {
				throw IllegalStateException("${mDef.file.name}: '${inCommand.joinToString(" ")}' failed:\n${vErrors.readText()}")
			}
			return vOutput
		} finally {
			vErrors.delete()
		}
	}

	// ============
	//  Names and types

	private fun identifier(inName: String): String = if (inName in kKotlinKeywords) "`$inName`" else inName

	/** The Kotlin class standing for [inRecord], declared now or queued. */
	private fun classFor(inRecord: CRecord): String = mClassOf.getOrPut(inRecord) {
		mPendingRecords += inRecord
		inRecord.typedefName ?: inRecord.tag!!
	}

	private fun enumType(inEnum: CEnum): String = mEnumAlias[inEnum] ?: if (inEnum.isUnsigned) "UInt" else "Int"

	/** The interop class of a C variable of type [inType] (`IntVar`, a struct class…); null for void and what cannot be bound. */
	private fun variableType(inType: CType): String? = when (val vType = inType.resolved()) {
		is CPrim -> vType.variable
		is CEnum -> if (vType.isUnsigned) "UIntVar" else "IntVar"
		is CPointerTo -> "CPointerVar<${variableType(vType.target) ?: "out CPointed"}>".replace("CPointerVar<out CPointed>", "COpaquePointerVar")
		is CRecord -> if (vType.spelling.isEmpty()) null else classFor(vType)
		is CArrayOf -> variableType(vType.element)
		is CFunctionType -> "CFunction<${signature(vType) ?: "*"}>"
		CVoid, is CUnsupported, is CTypedefRef -> null
	}

	/** `(P1, P2) -> R` of a C function type, or null when a type in it cannot be bound. */
	private fun signature(inType: CFunctionType): String? {
		if (inType.isVariadic) return null
		val vParams = inType.params.map { valueType(it.type, inIsParameter = false) ?: return null }
		val vResult = if (inType.result.resolved() == CVoid) "Unit" else valueType(inType.result, inIsParameter = false) ?: return null
		return "(${vParams.joinToString(", ")}) -> $vResult"
	}

	/**
	 * The Kotlin type of a C value of type [inType]: as a parameter (`String?` for `const char*`,
	 * `CValuesRef<T>?` for other pointers) or as a result or field (`CPointer<T>?`). Null when it
	 * cannot be bound — a struct by value, an unsupported type.
	 */
	private fun valueType(inType: CType, inIsParameter: Boolean): String? = when (val vType = inType.resolved()) {
		is CPrim -> vType.kotlin
		is CEnum -> enumType(vType)
		is CPointerTo -> {
			val vTarget = vType.target.resolved()
			val vVariable = variableType(vTarget)
			when {
				inIsParameter && vType.isTargetConst && vTarget is CPrim && vTarget.kotlin == "Byte" -> "String?"
				vTarget is CUnsupported -> null
				vVariable == null -> if (inIsParameter) "CValuesRef<*>?" else "COpaquePointer?"
				// A function is only ever handled through its pointer.
				vTarget is CFunctionType -> "CPointer<$vVariable>?"
				else -> (if (inIsParameter) "CValuesRef" else "CPointer") + "<$vVariable>?"
			}
		}
		is CArrayOf -> variableType(vType.element)?.let { (if (inIsParameter) "CValuesRef" else "CPointer") + "<$it>?" }
		// A struct by value; one that is incomplete or has no name cannot be passed.
		is CRecord -> if (vType.fields != null && vType.spelling.isNotEmpty()) "CValue<${identifier(classFor(vType))}>" else null
		CVoid, is CFunctionType, is CUnsupported, is CTypedefRef -> null
	}

	/** How C names [inType], for a cast: only needed, and only produced, for function pointers. */
	private fun cSpelling(inType: CType): String? = when (inType) {
		is CTypedefRef -> inType.name
		CVoid -> "void"
		is CRecord -> inType.spelling.takeIf { it.isNotEmpty() }
		is CPointerTo -> when (val vTarget = inType.target) {
			is CFunctionType -> {
				val vResult = cSpelling(vTarget.result)
				val vParams = vTarget.params.map { cSpelling(it.type) }
				if (vResult == null || vParams.any { it == null }) null
				else "$vResult (*)(${(vParams + listOfNotNull("...".takeIf { vTarget.isVariadic })).joinToString(", ").ifEmpty { "void" }})"
			}
			else -> cSpelling(vTarget)?.let { (if (inType.isTargetConst) "const " else "") + "$it*" }
		}
		is CPrim -> when (inType.kotlin) {
			"Boolean" -> "_Bool"
			"Byte" -> "char"
			"UByte" -> "unsigned char"
			"Short" -> "short"
			"UShort" -> "unsigned short"
			"Int" -> "int"
			"UInt" -> "unsigned int"
			"Long" -> "long long"
			"ULong" -> "unsigned long long"
			"Float" -> "float"
			else -> "double"
		}
		is CEnum -> inType.tag?.let { "enum $it" } ?: inType.typedefName
		is CArrayOf, is CFunctionType, is CUnsupported -> null
	}

	private fun isPointer(inType: CType): Boolean = inType.resolved().let { it is CPointerTo || it is CArrayOf }

	private fun isFunctionPointer(inType: CType): Boolean = (inType.resolved() as? CPointerTo)?.target?.resolved() is CFunctionType

	// ============
	//  Declarations

	private fun enumeration(inEnum: CEnum) {
		val vBase = if (inEnum.isUnsigned) "UInt" else "Int"
		val vName = inEnum.typedefName ?: inEnum.tag
		mOut.append("\n")
		if (vName != null && mDeclared.add(vName)) {
			mOut.append("public typealias ${identifier(vName)} = $vBase\n")
			mEnumAlias[inEnum] = identifier(vName)
		}
		val vType = enumType(inEnum)
		for ((vConstant, vValue) in inEnum.constants) {
			if (!mDeclared.add(vConstant)) continue
			if (vValue != null) {
				mOut.append("public const val ${identifier(vConstant)}: $vType = ${vValue}${if (inEnum.isUnsigned) "u" else ""}\n")
			} else {
				mOut.append("public val ${identifier(vConstant)}: $vType get() = cExpr(\"$vConstant\")\n")
			}
		}
	}

	private fun record(inRecord: CRecord, inIsWanted: (String) -> Boolean) {
		val vName = mClassOf.getValue(inRecord)
		if (!mDeclared.add("class $vName")) return
		val vFields = inRecord.fields?.takeIf { inIsWanted(inRecord.file) }
		val vSpelling = inRecord.spelling
		mOut.append("\n")
		if (inRecord.fields == null) {
			// Incomplete in C too: it can be pointed at, not allocated.
			mOut.append("public class ${identifier(vName)} private constructor() : COpaque()\n")
			return
		}
		mOut.append("@CType(\"$vSpelling\")\npublic class ${identifier(vName)} private constructor() : CStructVar()")
		if (vFields.isNullOrEmpty()) {
			mOut.append("\n")
			return
		}
		mOut.append(" {\n")
		for (vField in vFields) {
			val vAccess = "(($vSpelling*)\$0)->${vField.name}"
			val vFieldName = identifier(vField.name)
			val vType = vField.type.resolved()
			when {
				vType is CRecord -> {
					// A struct inside the struct: the field is that struct, in place.
					if (vType.spelling.isEmpty()) mOut.append("\t// skipped: ${vField.name} (a struct without a name)\n")
					else mOut.append("\tpublic val $vFieldName: ${identifier(classFor(vType))} get() = cExpr(\"(void*)&$vAccess\", this)\n")
				}
				vType is CArrayOf -> {
					val vElement = variableType(vType.element)
					if (vElement == null) mOut.append("\t// skipped: ${vField.name} (an array of an unsupported type)\n")
					else mOut.append("\tpublic val $vFieldName: CArrayPointer<$vElement> get() = cExpr(\"(void*)$vAccess\", this)\n")
				}
				else -> {
					val vKotlin = valueType(vField.type, inIsParameter = false)
					if (vKotlin == null) {
						mOut.append("\t// skipped: ${vField.name} (an unsupported type)\n")
					} else {
						val vRead = if (isPointer(vField.type)) "(void*)$vAccess" else vAccess
						mOut.append("\tpublic var $vFieldName: $vKotlin\n")
						mOut.append("\t\tget() = cExpr(\"$vRead\", this)\n")
						mOut.append("\t\tset(value) {\n\t\t\tcExpr<Unit>(\"$vAccess = \$1\", this, value)\n\t\t}\n")
					}
				}
			}
		}
		mOut.append("}\n")
	}

	private fun function(inFunction: CFunctionDecl) {
		val vName = inFunction.name
		if (vName.startsWith("__builtin") || !mDeclared.add("fun $vName")) return
		val vType = inFunction.type
		val vIsVoid = vType.result.resolved() == CVoid
		val vResult = if (vIsVoid) "Unit" else valueType(vType.result, inIsParameter = false)
		val vParamTypes = vType.params.map { valueType(it.type, inIsParameter = true) }
		if (vResult == null || vParamTypes.any { it == null }) {
			mOut.append("\n// skipped: $vName (a parameter or the result has a type that cannot be bound)\n")
			mDeclared.remove("fun $vName")
			return
		}
		val vNames = ArrayList<String>()
		vType.params.forEachIndexed { vIndex, vParam ->
			var vParamName = vParam.name ?: "arg$vIndex"
			while (vParamName in vNames || vParamName == "variadicArguments") vParamName += "_"
			vNames += vParamName
		}
		val vArguments = vType.params.mapIndexed { vIndex, vParam ->
			// A function pointer does not convert from void* in standard C: it is cast to its type.
			val vCast = if (isFunctionPointer(vParam.type)) cSpelling(vParam.type)?.let { "($it)" } ?: "" else ""
			// A struct by value is read out of the CValue that holds it.
			(vParam.type.resolved() as? CRecord)?.let { "(*(${it.spelling}*)ktc2_cvalue_data(\$$vIndex))" } ?: "$vCast\$$vIndex"
		}
		val vCall = "$vName(${vArguments.joinToString(", ")}${if (vType.isVariadic) "\$*" else ""})"
		val vRecord = vType.result.resolved() as? CRecord
		val vText = when {
			// The returned struct is copied into a new CValue.
			vRecord != null -> "ktc2_cvalue_copy((${vRecord.spelling}[1]){ $vCall }, sizeof(${vRecord.spelling}))"
			isPointer(vType.result) -> "(void*)$vCall"
			else -> vCall
		}
		val vDeclared = vNames.mapIndexed { vIndex, vParamName -> "${identifier(vParamName)}: ${vParamTypes[vIndex]}" }
		mOut.append("\n")
		if (vType.isVariadic) {
			// The extra arguments of each call are passed as they are; the body is never used.
			mOut.append("@CVariadic(\"$vText\")\n")
			mOut.append("public fun ${identifier(vName)}(${(vDeclared + "vararg variadicArguments: Any?").joinToString(", ")}): $vResult = throw NotImplementedError()\n")
			return
		}
		val vPassed = (listOf("\"$vText\"") + vNames.map { identifier(it) }).joinToString(", ")
		if (vIsVoid) {
			mOut.append("public fun ${identifier(vName)}(${vDeclared.joinToString(", ")}) {\n\tcExpr<Unit>($vPassed)\n}\n")
		} else {
			mOut.append("public fun ${identifier(vName)}(${vDeclared.joinToString(", ")}): $vResult = cExpr($vPassed)\n")
		}
	}

	/** A global variable of the library: a property that reads and writes it where it is. */
	private fun variable(inVariable: CVariableDecl) {
		val vName = inVariable.name
		if (vName.startsWith("_") || vName in mDeclared) return
		if (vName in mClassOf.values) {
			// Kotlin has one name space for classes and properties.
			mOut.append("\n// skipped: $vName (a struct has the same name)\n")
			return
		}
		val vType = inVariable.type.resolved()
		val vKotlin = identifier(vName)
		val vDeclaration = when {
			vType is CRecord -> if (vType.spelling.isEmpty() || vType.fields == null) null else "public val $vKotlin: ${identifier(classFor(vType))} get() = cExpr(\"(void*)&$vName\")\n"
			vType is CArrayOf -> variableType(vType.element)?.let { "public val $vKotlin: CArrayPointer<$it> get() = cExpr(\"(void*)$vName\")\n" }
			else -> valueType(inVariable.type, inIsParameter = false)?.let { vValue ->
				val vRead = if (isPointer(inVariable.type)) "(void*)$vName" else vName
				if (inVariable.isConst) "public val $vKotlin: $vValue get() = cExpr(\"$vRead\")\n"
				else "public var $vKotlin: $vValue\n\tget() = cExpr(\"$vRead\")\n\tset(value) {\n\t\tcExpr<Unit>(\"$vName = \$0\", value)\n\t}\n"
			}
		}
		if (vDeclaration == null) {
			mOut.append("\n// skipped: $vName (a variable of a type that cannot be bound)\n")
			return
		}
		mDeclared += vName
		mOut.append("\n").append(vDeclaration)
	}

	private fun macro(inMacro: CMacro, inParser: CHeaderParser) {
		val vName = inMacro.name
		val vBody = inMacro.body
		if (vBody.isEmpty() || vName.startsWith("_") || vName in mDeclared) return
		val vFloat = Regex("^\\(?(-?(?:\\d+\\.\\d*|\\.\\d+|\\d+)(?:[eE][-+]?\\d+)?)([fF]?)\\)?$").find(vBody)
		val vString = Regex("^\"((?:[^\"\\\\]|\\\\.)*)\"$").find(vBody)
		val vInteger = inParser.macroInteger(vBody)
		val vDeclaration = when {
			vInteger != null -> {
				val (vValue, vIsUnsigned) = vInteger
				when {
					vIsUnsigned && vValue in 0..0xFFFFFFFFL -> "UInt = ${vValue}u"
					vIsUnsigned -> "ULong = ${vValue.toULong()}uL"
					vValue in Int.MIN_VALUE..Int.MAX_VALUE -> "Int = $vValue"
					vValue == Long.MIN_VALUE -> "Long = Long.MIN_VALUE"
					else -> "Long = ${vValue}L"
				}
			}
			vFloat != null && ('.' in vBody || 'e' in vBody.lowercase()) ->
				vFloat.groupValues[1].replace(Regex("\\.(?=$|[eE])"), ".0").let { if (vFloat.groupValues[2].isEmpty()) "Double = $it" else "Float = ${it}f" }
			// Only the escapes Kotlin shares with C.
			vString != null && Regex("\\\\[^nrtb\\\\\"']").find(vString.groupValues[1]) == null ->
				"String = \"${vString.groupValues[1].replace("$", "\\$")}\""
			else -> return
		}
		mDeclared += vName
		mOut.append("\npublic const val ${identifier(vName)}: $vDeclaration\n")
	}
}
