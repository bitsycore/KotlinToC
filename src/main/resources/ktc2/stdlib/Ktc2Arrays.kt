/** Moves the element at [inRoot] down the heap of [inCount] elements that starts at [inFrom]. */
private fun siftDown(inArray: ByteArray, inFrom: Int, inRoot: Int, inCount: Int) {
	var vRoot = inRoot
	while (true) {
		var vChild = 2 * vRoot + 1
		if (vChild >= inCount) return
		if (vChild + 1 < inCount && inArray[inFrom + vChild].compareTo(inArray[inFrom + vChild + 1]) < 0) vChild++
		if (inArray[inFrom + vRoot].compareTo(inArray[inFrom + vChild]) >= 0) return
		val vSwap = inArray[inFrom + vRoot]
		inArray[inFrom + vRoot] = inArray[inFrom + vChild]
		inArray[inFrom + vChild] = vSwap
		vRoot = vChild
	}
}

/** Heap sort of `[inFrom, inTo)`: in place, and never worse than n log n. */
private fun sortRange(inArray: ByteArray, inFrom: Int, inTo: Int) {
	val vCount = inTo - inFrom
	var vStart = vCount / 2
	while (vStart > 0) {
		vStart--
		siftDown(inArray, inFrom, vStart, vCount)
	}
	var vEnd = vCount
	while (vEnd > 1) {
		vEnd--
		val vSwap = inArray[inFrom]
		inArray[inFrom] = inArray[inFrom + vEnd]
		inArray[inFrom + vEnd] = vSwap
		siftDown(inArray, inFrom, 0, vEnd)
	}
}

public actual fun ByteArray.sort(): Unit {
	if (size > 1) sortRange(this, 0, size)
}

public actual fun ByteArray.sort(fromIndex: Int, toIndex: Int): Unit {
	checkRange(fromIndex, toIndex, size)
	sortRange(this, fromIndex, toIndex)
}

