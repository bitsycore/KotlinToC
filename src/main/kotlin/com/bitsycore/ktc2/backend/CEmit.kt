package com.bitsycore.ktc2.backend

import com.bitsycore.ktc2.kir.*
import java.io.File

private val kRuntimeFiles = listOf("ktc2_core.h", "ktc2_core.c")

/**
 * Prints a [KModule] as C11: one `.h` / `.c` pair per [KUnit], the runtime, `ktc2_types.h`
 * (type ids) and `ktc2_main.c` (type table, startup, `main`).
 * KIR is already in statement form, so this is a direct print with no analysis.
 */
class CEmitter(private val mModule: KModule) {

	/** Classes the program instantiates, in type-id order. */
	private val mConcrete = mModule.classes.filter { it.isInstantiated }

	/**
	 * Writes all files under [inRoot].
	 *
	 * @return the `.c` files to compile, relative to [inRoot]
	 */
	private fun config(): String = buildString {
		append("/* Generated by ktc2: how the runtime is built for this program. */\n")
		append("#ifndef KTC2__BUILD_CONFIG\n#define KTC2__BUILD_CONFIG\n\n")
		if (mModule.usesThreads) append("/* The program starts threads: reference counts are atomic. */\n#define KTC2_THREADS 1\n\n")
		if (mModule.throwers.isNotEmpty()) append("/* An index out of bounds or a division by zero throws instead of ending the program. */\n#define KTC2_CHECKS_THROW 1\n\n")
		append("#endif\n")
	}

	fun emit(inRoot: File): List<String> {
		val vSources = ArrayList<String>()
		write(File(inRoot, "ktc2_types.h"), typeIds())
		write(File(inRoot, "ktc2_config.h"), config())
		for (vUnit in mModule.units) {
			write(File(inRoot, vUnit.path + ".h"), header(vUnit))
			write(File(inRoot, vUnit.path + ".c"), source(vUnit))
			vSources += vUnit.path + ".c"
		}
		for (vName in kRuntimeFiles) {
			val vText = javaClass.getResourceAsStream("/ktc2/$vName")!!.use { it.readBytes().decodeToString() }
			write(File(inRoot, vName), vText)
			if (vName.endsWith(".c")) vSources += vName
		}
		mModule.entry?.let { vEntry ->
			write(File(inRoot, "ktc2_main.c"), program(vEntry))
			vSources += "ktc2_main.c"
		}
		return vSources
	}

	/** Leaves an unchanged file untouched so the C build stays incremental. */
	private fun write(inFile: File, inText: String) {
		if (inFile.isFile && inFile.readText() == inText) return
		inFile.parentFile.mkdirs()
		inFile.writeText(inText)
	}

	// ==================
	// MARK: Program files
	// ==================

	private fun typeId(inClass: KClass): String = "KTC2_TYPE_${inClass.cName}"

	private fun typeIds(): String = buildString {
		append("#ifndef KTC2_TYPES_H\n#define KTC2_TYPES_H\n\n#include \"ktc2_core.h\"\n\n")
		append("/* Type ids of the classes this program instantiates. */\nenum {\n")
		mConcrete.forEachIndexed { vIndex, vClass ->
			append("\t${typeId(vClass)} = KTC2_TYPE_FIRST_USER${if (vIndex == 0) "" else " + $vIndex"},\n")
		}
		append("\tKTC2_TYPE_COUNT = KTC2_TYPE_FIRST_USER + ${mConcrete.size}\n};\n\n#endif\n")
	}

	private fun program(inEntry: KFunction): String = buildString {
		val vStartup = mModule.units.mapNotNull { it.initializer }
		val vGlobals = mModule.units.flatMap { it.globals }.filter { it.type.isCounted() }
		val vStatics = mModule.units.flatMap { it.statics }
		val vUnits = vStartup.map { it.unit } + mConcrete.map { it.unit } + vStatics.flatMap { listOf(it.unit, it.cls.unit) } + vGlobals.map { it.unit } + inEntry.unit
		append("#include \"ktc2_types.h\"\n")
		vUnits.distinct().forEach { append("#include \"${it.path}.h\"\n") }

		append("\nconst ktc2_TypeInfo ktc2_types[] = {\n\tKTC2_BUILTIN_TYPES,\n")
		mConcrete.forEach { vClass ->
			val vDeinit = if (vClass.deinit != null) "${vClass.cName}__deinit" else "NULL"
			append("\t[${typeId(vClass)}] = { ${cString(vClass.name)}, ${vClass.cName}__destroy, sizeof(${vClass.cName}), $vDeinit },\n")
		}
		append("};\n\nconst uint32_t ktc2_type_count = KTC2_TYPE_COUNT;\n")

		val vTakesArguments = inEntry.params.isNotEmpty()
		append(if (vTakesArguments) "\nint main(int argc, char** argv)\n{\n" else "\nint main(void)\n{\n")
		// An exception that reaches main unhandled ends the program, as on the JVM.
		vStartup.forEach { append("\t${it.cName}();\n\tif (ktc2_has_pending()) ktc2_uncaught();\n") }
		if (vTakesArguments) {
			// `fun main(args: Array<String>)`: the command line without the program's name.
			append("\tktc2_Array* arguments = ktc2_args(argc, argv);\n")
			append("\t${inEntry.cName}(arguments);\n\tif (ktc2_has_pending()) ktc2_uncaught();\n\tktc2_release(arguments);\n")
		} else {
			append("\t${inEntry.cName}();\n\tif (ktc2_has_pending()) ktc2_uncaught();\n")
		}
		// What the top-level properties and the objects still hold is given up without `deinit`.
		append("\tktc2_ending();\n")
		vGlobals.asReversed().forEach { append("\t${releaseText(it.type, it.cName)};\n") }
		vStatics.asReversed().forEach { append("\t${it.cls.cName}__destroy((ktc2_Obj*)&${it.cName});\n") }
		append("\treturn ktc2_exit();\n}\n")
	}

	// ==================
	// MARK: Units
	// ==================

	private fun unitOf(inType: KType): KUnit? = (inType as? KStructType)?.struct?.unit

	private fun cType(inType: KType): String = when (inType) {
		is KPrimType -> inType.prim.cName
		is KOptType -> "ktc2_Opt_${inType.prim.cName}"
		is KStructType -> inType.struct.cName
		KPtrType -> "void*"
		KStringType -> "ktc2_String*"
		is KClassType -> "${inType.cls.cName}*"
		KObjType -> "ktc2_Obj*"
		is KArrayType -> "ktc2_Array*"
		KUnitType, KNothingType -> "void"
	}

	private fun signature(inFunction: KFunction): String {
		val vParams = if (inFunction.params.isEmpty()) "void" else inFunction.params.joinToString(", ") { "${cType(it.type)} ${it.cName}" }
		return "${cType(inFunction.returnType)} ${inFunction.cName}($vParams)"
	}

	private fun allFunctions(inUnit: KUnit): List<KFunction> = inUnit.functions + listOfNotNull(inUnit.initializer)

	/** Reference fields of [inClass] itself (not inherited). */
	private fun refFields(inClass: KClass): List<KField> = inClass.fields.filter { it.type.isCounted() && !it.isInline }

	/** C that takes a reference to [inText]: the object's count, or those of everything a struct holds. Yields the value. */
	private fun retainText(inType: KType, inText: String): String =
		if (inType is KStructType) "${inType.struct.cName}__retain($inText)" else "ktc2_retain($inText)"

	private fun releaseText(inType: KType, inText: String): String =
		if (inType is KStructType) "${inType.struct.cName}__release($inText)" else "ktc2_release($inText)"

	/** The C declaration of a field: a pointer, a value, or inline storage. */
	private fun fieldDeclaration(inField: KField): String {
		val vType = inField.type
		return when {
			inField.inlineSize == 0 -> "${(vType as KClassType).cls.cName} ${inField.cName}"
			inField.inlineSize > 0 -> "struct { ktc2_Array header; ${cType((vType as KArrayType).element)} data[${inField.inlineSize}]; } ${inField.cName}"
			else -> "${cType(vType)} ${inField.cName}"
		}
	}

	private fun headerPath(inClass: KClass): String =
		generateSequence(inClass) { it.superClass }.drop(1).joinToString("") { "._super" } + "._header"

	private fun arrayId(inElement: KType): String = when (inElement) {
		is KPrimType -> "KTC2_TYPE_ARRAY_${inElement.prim.name}"
		is KRefType -> "KTC2_TYPE_ARRAY_REF"
		else -> "KTC2_TYPE_ARRAY_VALUE"
	}

	private fun header(inUnit: KUnit): String = buildString {
		val vGuard = "KTC2_UNIT_" + inUnit.path.uppercase().map { if (it.isLetterOrDigit()) it else '_' }.joinToString("") + "_H"
		append("#ifndef $vGuard\n#define $vGuard\n\n#include \"ktc2_core.h\"\n")

		// By-value types need the full definition; classes are only used through pointers,
		// so a forward declaration is enough and headers never include each other in a cycle.
		val vTypes = ArrayList<KType>()
		inUnit.struct?.fields?.forEach { vTypes += it.type }
		inUnit.cls?.fields?.forEach { vTypes += it.type }
		inUnit.globals.forEach { vTypes += it.type }
		for (vFunction in allFunctions(inUnit)) {
			vTypes += vFunction.returnType
			vFunction.params.forEach { vTypes += it.type }
		}
		val vIncludes = LinkedHashSet<KUnit>()
		vTypes.forEach { vType -> unitOf(vType)?.let(vIncludes::add) }
		inUnit.cls?.superClass?.let { vIncludes += it.unit }
		// An object stored inline needs its full definition here.
		inUnit.cls?.fields?.filter { it.inlineSize == 0 }?.forEach { vIncludes += (it.type as KClassType).cls.unit }
		vIncludes.filter { it !== inUnit }.forEach { append("#include \"${it.path}.h\"\n") }
		append("\n")
		val vForward = LinkedHashSet<KClass>()
		inUnit.cls?.let(vForward::add)
		vTypes.forEach { vType -> (vType as? KClassType)?.let { vForward += it.cls } }
		inUnit.statics.forEach { vForward += it.cls }
		vForward.forEach { append("typedef struct ${it.cName} ${it.cName};\n") }
		if (vForward.isNotEmpty()) append("\n")

		inUnit.struct?.let { vStruct ->
			append("typedef struct ${vStruct.cName} {\n")
			if (vStruct.fields.isEmpty()) append("\tchar _empty;\n")
			vStruct.fields.forEach { append("\t${cType(it.type)} ${it.cName};\n") }
			append("} ${vStruct.cName};\n\n")
			if (vStruct.holdsReferences) {
				val vCounted = vStruct.fields.filter { it.type.isCounted() }
				append("/** Takes a reference to everything the value refers to; yields the value. */\n")
				append("static inline ${vStruct.cName} ${vStruct.cName}__retain(${vStruct.cName} value)\n{\n")
				vCounted.forEach { append("\t${retainText(it.type, "value.${it.cName}")};\n") }
				append("\treturn value;\n}\n\n")
				append("/** Gives up the references the value holds. */\n")
				append("static inline void ${vStruct.cName}__release(${vStruct.cName} value)\n{\n")
				vCounted.forEach { append("\t${releaseText(it.type, "value.${it.cName}")};\n") }
				append("}\n\n")
			}
		}
		inUnit.cls?.let { vClass ->
			append("struct ${vClass.cName} {\n")
			append(vClass.superClass?.let { "\t${it.cName} _super;\n" } ?: "\tktc2_Obj _header;\n")
			vClass.fields.forEach { append("\t${fieldDeclaration(it)};\n") }
			append("};\n\n")
			append("/** Releases the references held by the fields of an instance. */\n")
			append("void ${vClass.cName}__destroy(ktc2_Obj* object);\n")
			append("/** Takes a reference on everything the fields of an instance refer to (after a bitwise copy). */\n")
			append("void ${vClass.cName}__retain_fields(${vClass.cName}* self);\n")
			if (vClass.deinit != null) {
				append("/** Calls `deinit` of an instance nothing refers to any more. */\n")
				append("void ${vClass.cName}__deinit(ktc2_Obj* object);\n")
			}
			if (vClass.isUsedInline) {
				append("/** A heap copy of an instance (the boxed form of an inline value). */\n")
				append("${vClass.cName}* ${vClass.cName}__clone(const ${vClass.cName}* source);\n")
				append("/** Replaces the content of an inline slot by a copy of [source]. */\n")
				append("void ${vClass.cName}__assign(${vClass.cName}* slot, const ${vClass.cName}* source);\n")
			}
		}
		inUnit.statics.forEach { append("extern ${it.cls.cName} ${it.cName};\n") }
		inUnit.globals.forEach { append("extern ${cType(it.type)} ${it.cName};\n") }
		allFunctions(inUnit).forEach { append(signature(it)).append(";\n") }
		append("\n#endif\n")
	}

	private fun source(inUnit: KUnit): String {
		val vBodies = StringBuilder()
		val vState = UnitState()
		val vPrinter = FunctionPrinter(vBodies, vState)

		for (vStatic in inUnit.statics) {
			vState.includes += vStatic.cls.unit
			val vPath = generateSequence(vStatic.cls) { it.superClass }.drop(1).joinToString("") { "._super" } + "._header"
			vBodies.append("\n${vStatic.cls.cName} ${vStatic.cName} = { $vPath = { KTC2_IMMORTAL, ${typeId(vStatic.cls)} } };\n")
		}
		inUnit.cls?.let { vClass ->
			vBodies.append("\nvoid ${vClass.cName}__destroy(ktc2_Obj* object)\n{\n")
			val vOwn = refFields(vClass)
			if (vOwn.isNotEmpty()) vBodies.append("\t${vClass.cName}* self = (${vClass.cName}*)object;\n")
			vOwn.forEach { vBodies.append("\t${releaseText(it.type, "self->${it.cName}")};\n") }
			val vInline = vClass.fields.filter { it.isInline }
			if (vInline.isNotEmpty() && vOwn.isEmpty()) vBodies.append("\t${vClass.cName}* self = (${vClass.cName}*)object;\n")
			for (vField in vInline) {
				val vType = vField.type
				if (vType is KClassType) {
					vState.includes += vType.cls.unit
					vBodies.append("\t${vType.cls.cName}__destroy((ktc2_Obj*)&self->${vField.cName});\n")
				} else if ((vType as KArrayType).element is KRefType) {
					vBodies.append("\tif (self->${vField.cName}.header.length) ktc2_array_destroy((ktc2_Obj*)&self->${vField.cName});\n")
				}
			}
			vClass.superClass?.let {
				vState.includes += it.unit
				vBodies.append("\t${it.cName}__destroy(object);\n")
			}
			if (vOwn.isEmpty() && vClass.superClass == null) vBodies.append("\t(void)object;\n")
			vBodies.append("}\n")
			vClass.deinit?.let { vDeinit ->
				vState.includes += vDeinit.unit
				vBodies.append("\nvoid ${vClass.cName}__deinit(ktc2_Obj* object)\n{\n")
				vBodies.append("\t${vDeinit.cName}((${cType(vDeinit.params[0].type)})object);\n}\n")
			}
		}
		inUnit.cls?.let { vClass ->
			val vName = vClass.cName
			vBodies.append("\nvoid ${vName}__retain_fields($vName* self)\n{\n")
			refFields(vClass).forEach { vBodies.append("\t${retainText(it.type, "self->${it.cName}")};\n") }
			for (vField in vClass.fields.filter { it.isInline }) {
				val vType = vField.type
				if (vType is KClassType) {
					vBodies.append("\t${vType.cls.cName}__retain_fields(&self->${vField.cName});\n")
				} else if ((vType as KArrayType).element is KRefType) {
					vBodies.append("\tfor (int32_t i = 0; i < self->${vField.cName}.header.length; i++) ktc2_retain(self->${vField.cName}.data[i]);\n")
				}
			}
			vClass.superClass?.let { vBodies.append("\t${it.cName}__retain_fields(&self->_super);\n") }
			vBodies.append("\t(void)self;\n}\n")
			if (vClass.isUsedInline) {
				val vHeader = "(ktc2_Obj){ KTC2_IMMORTAL, ${typeId(vClass)} }"
				vBodies.append("\n$vName* ${vName}__clone(const $vName* source)\n{\n")
				vBodies.append("\t$vName* copy = ktc2_alloc(sizeof($vName), ${typeId(vClass)});\n")
				vBodies.append("\tktc2_Obj header = *(ktc2_Obj*)copy;\n\t*copy = *source;\n\t*(ktc2_Obj*)copy = header;\n")
				vBodies.append("\t${vName}__retain_fields(copy);\n\treturn copy;\n}\n")
				vBodies.append("\nvoid ${vName}__assign($vName* slot, const $vName* source)\n{\n")
				vBodies.append("\tif (slot == source) return;\n")
				vBodies.append("\t$vName previous = *slot;\n\t*slot = *source;\n\t*(ktc2_Obj*)slot = $vHeader;\n")
				vBodies.append("\t${vName}__retain_fields(slot);\n\t${vName}__destroy((ktc2_Obj*)&previous);\n}\n")
			}
		}
		if (inUnit.globals.isNotEmpty()) vBodies.append("\n")
		for (vGlobal in inUnit.globals) {
			val vInit = vGlobal.constInit?.let { " = ${vPrinter.constant(it)}" } ?: ""
			vBodies.append("${cType(vGlobal.type)} ${vGlobal.cName}$vInit;\n")
		}
		for (vFunction in allFunctions(inUnit)) {
			vBodies.append("\n").append(signature(vFunction)).append("\n{\n")
			if (vFunction.dispatch != null) {
				vPrinter.dispatcher(vFunction)
			} else {
				vPrinter.block(vFunction.body, 1)
				// Kotlin has checked that every path returns or throws; the C compiler has not.
				val vReturns = vFunction.returnType != KUnitType && vFunction.returnType != KNothingType
				if (vReturns && vFunction.body.lastOrNull() !is KReturn) vBodies.append("\treturn ${vPrinter.zero(vFunction.returnType)};\n")
			}
			vBodies.append("}\n")
		}

		return buildString {
			append("#include \"${inUnit.path}.h\"\n#include \"ktc2_types.h\"\n")
			vState.includes.filter { it !== inUnit && it.name != "ktc2_core" }.forEach { append("#include \"${it.path}.h\"\n") }
			vState.cHeaders.forEach { append("#include $it\n") }
			if (vState.literals.isNotEmpty()) append("\n")
			vState.literals.forEach { (vText, vName) ->
				append("KTC2_STRING_LIT($vName, ${vText.encodeToByteArray().size}, ${vText.length}, ${cString(vText)});\n")
			}
			vState.typeTests.forEachIndexed { vIndex, vIds ->
				append("\nstatic bool is_$vIndex(const void* object)\n{\n\tif (!object) return false;\n")
				if (vIds.isEmpty()) {
					append("\treturn false;\n}\n")
				} else {
					append("\tswitch (((const ktc2_Obj*)object)->typeId) {\n")
					vIds.forEach { append("\tcase $it:\n") }
					append("\t\treturn true;\n\tdefault:\n\t\treturn false;\n\t}\n}\n")
				}
			}
			vState.trampolines.values.forEach { append(trampoline(it)) }
			append(vBodies)
		}
	}

	/** The C function [inTrampoline] describes: structs by value on the C side, `CValue`s on the Kotlin side. */
	private fun trampoline(inTrampoline: KTrampoline): String = buildString {
		val vTarget = inTrampoline.target
		val vIsVoid = vTarget.returnType == KUnitType
		val vResultType = inTrampoline.resultSpelling ?: if (vIsVoid) "void" else cType(vTarget.returnType)
		val vParams = vTarget.params.mapIndexed { vIndex, vParam -> "${inTrampoline.paramSpellings[vIndex] ?: cType(vParam.type)} p$vIndex" }
		append("\nstatic $vResultType ${inTrampoline.name}(${vParams.joinToString(", ").ifEmpty { "void" }})\n{\n")
		val vArguments = vTarget.params.indices.map { vIndex ->
			if (inTrampoline.paramSpellings[vIndex] == null) {
				"p$vIndex"
			} else {
				append("\tktc2_Array* v$vIndex = ktc2_cvalue_copy(&p$vIndex, sizeof p$vIndex);\n")
				"v$vIndex"
			}
		}
		val vCall = "${vTarget.cName}(${vArguments.joinToString(", ")})"
		append(if (vIsVoid) "\t$vCall;\n" else "\t${cType(vTarget.returnType)} result = $vCall;\n")
		vTarget.params.indices.filter { inTrampoline.paramSpellings[it] != null }.forEach { append("\tktc2_release(v$it);\n") }
		if (inTrampoline.resultSpelling != null) {
			// Nothing is returned by a function that left with an exception: C then receives zeroes.
			append("\t$vResultType value;\n\tmemset(&value, 0, sizeof value);\n")
			append("\tif (result) {\n\t\tmemcpy(&value, ktc2_cvalue_data(result), sizeof value);\n\t\tktc2_release(result);\n\t}\n\treturn value;\n")
		} else if (!vIsVoid) {
			append("\treturn result;\n")
		}
		append("}\n")
	}

	/** What a `.c` file collects while its functions are printed. */
	private class UnitState {
		val includes = LinkedHashSet<KUnit>()

		/** C headers of the libraries this unit calls into. */
		val cHeaders = LinkedHashSet<String>()

		/** The C functions standing in front of callbacks that take or return structs by value, by name. */
		val trampolines = LinkedHashMap<String, KTrampoline>()
		val literals = LinkedHashMap<String, String>()
		val typeTests = ArrayList<List<String>>()
	}

	/** A C string literal holding the UTF-8 bytes of [inText]. */
	private fun cString(inText: String): String = buildString {
		append('"')
		for (vByte in inText.encodeToByteArray()) {
			val vCode = vByte.toInt() and 0xFF
			when {
				vCode == '"'.code -> append("\\\"")
				vCode == '\\'.code -> append("\\\\")
				vCode == '\n'.code -> append("\\n")
				vCode == '\t'.code -> append("\\t")
				vCode in 32..126 && vCode != '?'.code -> append(vCode.toChar())
				else -> append('\\').append(vCode.toString(8).padStart(3, '0'))
			}
		}
		append('"')
	}

	// ==================
	// MARK: Function bodies
	// ==================

	private inner class FunctionPrinter(
		private val mOut: StringBuilder,
		private val mState: UnitState,
	) {
		/** Enclosing loops, innermost last. */
		private val mLoops = ArrayList<KLoop>()
		private val mBreakLabels = HashSet<Int>()
		private val mContinueLabels = HashSet<Int>()

		fun block(inStatements: List<KStmt>, inDepth: Int) {
			inStatements.forEach { statement(it, inDepth) }
		}

		private fun line(inDepth: Int, inText: String) {
			repeat(inDepth) { mOut.append('\t') }
			mOut.append(inText).append('\n')
		}

		private fun need(inType: KType) {
			when (inType) {
				is KStructType -> mState.includes += inType.struct.unit
				is KClassType -> mState.includes += inType.cls.unit
				else -> {}
			}
		}

		/** Body of a virtual dispatcher: a switch on the receiver's type id. */
		fun dispatcher(inFunction: KFunction) {
			val vSelf = inFunction.params[0].cName
			val vIsVoid = inFunction.returnType == KUnitType
			// The dispatcher and an implementation can differ in representation: a pointer cast
			// between reference types, and boxing where one side is erased and the other is not.
			fun adapt(inText: String, inFrom: KType, inTo: KType): String = when {
				inFrom == inTo -> inText
				inFrom is KRefType && inTo is KStructType -> {
					val vBox = inTo.struct.box!!
					mState.includes += vBox.unit
					"((${vBox.cName}*)$inText)->value"
				}
				inFrom is KStructType && inTo is KRefType -> {
					val vBox = inFrom.struct.box!!
					mState.includes += vBox.unit
					"(${cType(inTo)})ktc2_box_value((${cType(inFrom)}[1]){ $inText }, sizeof(${cType(inFrom)}), ${typeId(vBox)}, offsetof(${vBox.cName}, value))"
				}
				inFrom is KRefType && inTo == KPtrType -> "ktc2_unbox_ptr((ktc2_Obj*)$inText)"
				inFrom == KPtrType && inTo is KRefType -> "(${cType(inTo)})ktc2_box_ptr($inText)"
				inFrom is KRefType && inTo is KPrimType -> "ktc2_unbox_${inTo.prim.name.lowercase()}((ktc2_Obj*)$inText)"
				inFrom is KRefType && inTo is KOptType -> "ktc2_unbox_opt_${inTo.prim.name.lowercase()}((ktc2_Obj*)$inText)"
				inFrom is KPrimType && inTo is KRefType -> "(${cType(inTo)})ktc2_box_${inFrom.prim.name.lowercase()}($inText)"
				inFrom is KOptType && inTo is KRefType -> "(${cType(inTo)})ktc2_box_opt_${inFrom.prim.name.lowercase()}($inText)"
				// A Java-declared parameter (`T!`) is nullable on the dispatcher's side only.
				inFrom is KOptType && inTo is KPrimType -> "($inText).v"
				inFrom is KPrimType && inTo is KOptType -> "((${cType(inTo)}){ true, $inText })"
				else -> "(${cType(inTo)})$inText"
			}
			fun isUnboxed(inType: KType): Boolean = inType is KPrimType || inType is KOptType || inType == KPtrType || inType is KStructType
			fun call(inTarget: KFunction): String {
				mState.includes += inTarget.unit
				// A value boxed for the implementation is a temporary of the dispatcher: released after the call.
				val vBefore = StringBuilder()
				val vAfter = StringBuilder()
				var vBoxes = 0
				val vArguments = inFunction.params.zip(inTarget.params).joinToString(", ") { (vFrom, vTo) ->
					// The box made for the call owns what the struct refers to, until it is released after the call.
					val vGiven = if (vFrom.type.isCounted() && vFrom.type is KStructType && vTo.type is KRefType) retainText(vFrom.type, vFrom.cName) else vFrom.cName
					val vText = adapt(vGiven, vFrom.type, vTo.type)
					if (isUnboxed(vFrom.type) && vTo.type is KRefType) {
						val vBox = "boxed${vBoxes++}"
						vBefore.append("${cType(vTo.type)} $vBox = $vText; ")
						vAfter.append("ktc2_release($vBox); ")
						vBox
					} else {
						vText
					}
				}
				val vCall = "${inTarget.cName}($vArguments)"
				if (vIsVoid) return "{ $vBefore$vCall; ${vAfter}return; }"
				if (inTarget.returnType == KUnitType || inTarget.returnType == KNothingType) return "{ $vBefore$vCall; ${vAfter}return ${zero(inFunction.returnType)}; }"
				if (inTarget.returnType is KRefType && isUnboxed(inFunction.returnType)) {
					// The implementation returns a box it owns: its content is taken out and the box released.
					// (NULL is what it returns when it left with an exception.)
					// The struct taken out of the box keeps its own references: the box is about to give up its ones.
					val vTaken = adapt("result", inTarget.returnType, inFunction.returnType)
					val vContent = if (inFunction.returnType.isCounted()) retainText(inFunction.returnType, vTaken) else vTaken
					val vValue = when (inFunction.returnType) {
						is KPrimType -> "result ? $vContent : 0"
						is KStructType -> "result ? $vContent : (${cType(inFunction.returnType)}){ 0 }"
						else -> vContent
					}
					return "{ $vBefore${cType(inTarget.returnType)} result = $vCall; $vAfter${cType(inFunction.returnType)} value = $vValue; ktc2_release(result); return value; }"
				}
				val vResult = adapt(vCall, inTarget.returnType, inFunction.returnType)
				if (vAfter.isEmpty()) return "return $vResult;"
				return "{ $vBefore${cType(inFunction.returnType)} result = $vResult; ${vAfter}return result; }"
			}
			line(1, "switch (((ktc2_Obj*)$vSelf)->typeId) {")
			for ((vClass, vTarget) in inFunction.dispatch!!) {
				mState.includes += vClass.unit
				line(1, "case ${typeId(vClass)}: ${call(vTarget)}")
			}
			if (inFunction.keepsDefault) {
				val vDefault = inFunction.dispatchDefault!!
				val vKeep = inFunction.params.last().cName
				val vArguments = inFunction.params.dropLast(1).joinToString(", ") { it.cName }
				line(1, "default: { ${cType(inFunction.returnType)} result = ${vDefault.cName}($vArguments); *(ktc2_Obj**)$vKeep = (ktc2_Obj*)result; return result; }")
				line(1, "}")
				return
			}
			line(1, "default: ${inFunction.dispatchDefault?.let { call(it) } ?: "ktc2_fail_dispatch_of(\"${inFunction.cName}\", ${vSelf} ? ((ktc2_Obj*)${vSelf})->typeId : 0);"}")
			line(1, "}")
		}

		private fun statement(inStatement: KStmt, inDepth: Int) {
			when (inStatement) {
				is KLet -> {
					need(inStatement.local.type)
					// A local without an initializer starts at zero: a path that leaves through a call
					// that always throws never assigns it, which the C compiler cannot know.
					val vInit = " = ${bare(expr(inStatement.init ?: KZero(inStatement.local.type)))}"
					line(inDepth, "${cType(inStatement.local.type)} ${inStatement.local.cName}$vInit;")
				}
				is KSet -> store(inStatement.local.cName, inStatement.value, inStatement.releasesOld, inDepth)
				is KGlobalSet -> {
					mState.includes += inStatement.global.unit
					store(inStatement.global.cName, inStatement.value, inStatement.releasesOld, inDepth)
				}
				is KFieldSet -> {
					val vField = inStatement.field
					val vSlot = field(inStatement.target, vField)
					val vType = vField.type
					when {
						vField.inlineSize == 0 -> {
							mState.includes += (vType as KClassType).cls.unit
							line(inDepth, "${vType.cls.cName}__assign(&$vSlot, ${bare(expr(inStatement.value))});")
						}
						vField.inlineSize > 0 -> {
							val vElement = (vType as KArrayType).element
							line(inDepth, "ktc2_array_assign((ktc2_Array*)&$vSlot, ${vField.inlineSize}, ${arrayId(vElement)}, sizeof(${cType(vElement)}), ${bare(expr(inStatement.value))});")
						}
						else -> store(vSlot, inStatement.value, inStatement.releasesOld, inDepth)
					}
				}
				is KIndexSet -> store(element(inStatement.array, inStatement.index, inStatement.value.type, inStatement.isChecked), inStatement.value, inStatement.releasesOld, inDepth)
				is KEval -> line(inDepth, "${bare(expr(inStatement.expr))};")
				is KRelease -> line(inDepth, "${releaseText(inStatement.operand.type, bare(expr(inStatement.operand)))};")
				is KReturn -> line(inDepth, inStatement.value?.let { "return ${bare(expr(it))};" } ?: "return;")
				is KIf -> ifChain(inStatement, inDepth)
				is KLoop -> loop(inStatement, inDepth)
				is KBreak -> {
					if (mLoops.last().id == inStatement.loopId) {
						line(inDepth, "break;")
					} else {
						mBreakLabels += inStatement.loopId
						line(inDepth, "goto break_${inStatement.loopId};")
					}
				}
				is KContinue -> {
					val vInner = mLoops.last()
					if (vInner.id == inStatement.loopId && vInner.latch.isEmpty()) {
						line(inDepth, "continue;")
					} else {
						mContinueLabels += inStatement.loopId
						line(inDepth, "goto continue_${inStatement.loopId};")
					}
				}
				is KPrint -> print(inStatement, inDepth)
				is KThrow, is KTryRegion -> error("exceptions are lowered before emission")
				is KConcat -> concat(inStatement, inDepth)
			}
		}

		private fun store(inSlot: String, inValue: KExpr, inReleasesOld: Boolean, inDepth: Int) {
			val vValue = bare(expr(inValue))
			val vType = inValue.type
			line(inDepth, when {
				!inReleasesOld -> "$inSlot = $vValue;"
				vType is KStructType -> "KTC2_ASSIGN_VALUE(${cType(vType)}, $inSlot, $vValue, ${vType.struct.cName}__release);"
				else -> "KTC2_ASSIGN($inSlot, $vValue);"
			})
		}

		private fun ifChain(inIf: KIf, inDepth: Int) {
			var vCurrent = inIf
			var vKeyword = "if"
			while (true) {
				line(inDepth, "$vKeyword (${bare(expr(vCurrent.condition))}) {")
				block(vCurrent.thenBlock, inDepth + 1)
				val vElse = vCurrent.elseBlock
				if (vElse.isEmpty()) break
				val vOnly = vElse.singleOrNull() as? KIf
				if (vOnly == null) {
					line(inDepth, "} else {")
					block(vElse, inDepth + 1)
					break
				}
				vCurrent = vOnly
				vKeyword = "} else if"
			}
			line(inDepth, "}")
		}

		private fun loop(inLoop: KLoop, inDepth: Int) {
			line(inDepth, "for (;;) {")
			// Loop ids are per function: forget labels requested by an earlier function's loop.
			mBreakLabels -= inLoop.id
			mContinueLabels -= inLoop.id
			mLoops += inLoop
			block(inLoop.body, inDepth + 1)
			if (inLoop.id in mContinueLabels) line(inDepth, "continue_${inLoop.id}: ;")
			block(inLoop.latch, inDepth + 1)
			mLoops.removeLast()
			line(inDepth, "}")
			if (inLoop.id in mBreakLabels) line(inDepth, "break_${inLoop.id}: ;")
		}

		// ============
		//  Text output

		private fun valueSuffix(inPrim: KPrim): String = when (inPrim) {
			KPrim.BOOLEAN -> "bool"
			KPrim.BYTE, KPrim.SHORT, KPrim.INT -> "int"
			KPrim.LONG -> "long"
			KPrim.CHAR -> "char"
			KPrim.FLOAT -> "float"
			KPrim.DOUBLE -> "double"
			KPrim.UBYTE, KPrim.USHORT, KPrim.UINT -> "uint"
			KPrim.ULONG -> "ulong"
		}

		/**
		 * Prints [inParts] through `<inPrefix>_<kind>(<inFirst>value)` calls: `ktc2_print` for
		 * stdout, `ktc2_sb` (with the builder as first argument) for string building.
		 */
		private fun parts(inParts: List<KPrintPart>, inPrefix: String, inFirst: String, inTrailer: String, inDepth: Int) {
			val vText = StringBuilder()
			fun flush() {
				if (vText.isEmpty()) return
				val vString = vText.toString()
				line(inDepth, "${inPrefix}_text($inFirst${cString(vString)}, ${vString.encodeToByteArray().size}, ${vString.length});")
				vText.clear()
			}
			for (vPart in inParts) {
				when (vPart) {
					is KPrintText -> vText.append(vPart.text)
					is KPrintValue -> {
						flush()
						val vValue = bare(expr(vPart.value))
						when (val vType = vPart.value.type) {
							is KPrimType -> line(inDepth, "${inPrefix}_${valueSuffix(vType.prim)}($inFirst$vValue);")
							is KOptType -> {
								line(inDepth, "if (${expr(vPart.value)}.has) {")
								line(inDepth + 1, "${inPrefix}_${valueSuffix(vType.prim)}($inFirst${expr(vPart.value)}.v);")
								line(inDepth, "} else {")
								line(inDepth + 1, "${inPrefix}_text($inFirst\"null\", 4, 4);")
								line(inDepth, "}")
							}
							else -> line(inDepth, "${inPrefix}_string($inFirst$vValue);")
						}
					}
				}
			}
			vText.append(inTrailer)
			flush()
		}

		private fun print(inPrint: KPrint, inDepth: Int) {
			parts(inPrint.parts, "ktc2_print", "", if (inPrint.newline) "\n" else "", inDepth)
		}

		private fun concat(inConcat: KConcat, inDepth: Int) {
			// A string that stays in this block is built in a buffer of the block when it fits.
			val vBuffer = "${inConcat.target.cName}_buffer"
			if (inConcat.onStack) line(inDepth, "_Alignas(ktc2_String) char $vBuffer[KTC2_STACK_STRING_SIZE];")
			line(inDepth, "{")
			line(inDepth + 1, "ktc2_Sb sb;")
			line(inDepth + 1, "ktc2_sb_init(&sb);")
			parts(inConcat.parts, "ktc2_sb", "&sb, ", "", inDepth + 1)
			val vFinish = if (inConcat.onStack) "ktc2_sb_finish_into(&sb, $vBuffer, sizeof $vBuffer)" else "ktc2_sb_finish(&sb)"
			line(inDepth + 1, "${inConcat.target.cName} = $vFinish;")
			line(inDepth, "}")
		}

		// ============
		//  Expressions

		/** Drops one pair of redundant outer parentheses. */
		private fun bare(inText: String): String {
			if (!inText.startsWith("(") || !inText.endsWith(")")) return inText
			var vDepth = 0
			for (vIndex in inText.indices) {
				if (inText[vIndex] == '(') vDepth++ else if (inText[vIndex] == ')') vDepth--
				if (vDepth == 0 && vIndex < inText.length - 1) return inText
			}
			return inText.substring(1, inText.length - 1)
		}

		private fun arguments(inArguments: List<KExpr>): String = inArguments.joinToString(", ") { bare(expr(it)) }

		private fun field(inTarget: KExpr, inField: KField): String {
			inField.owner?.let { mState.includes += it.unit }
			return "${expr(inTarget)}${if (inTarget.type is KClassType) "->" else "."}${inField.cName}"
		}

		/** The bounds-checked element `array[index]`, usable as a value or as a slot. */
		private fun element(inArray: KExpr, inIndex: KExpr, inType: KType, inIsChecked: Boolean): String {
			need(inType)
			val vAccess = if (inIsChecked) "KTC2_ARRAY_AT_UNCHECKED" else "KTC2_ARRAY_AT"
			return "$vAccess(${bare(expr(inArray))}, ${cType(inType)}, ${bare(expr(inIndex))})"
		}

		private fun arrayTypeId(inElement: KType): String = when (inElement) {
			is KPrimType -> "KTC2_TYPE_ARRAY_${inElement.prim.name}"
			is KRefType -> "KTC2_TYPE_ARRAY_REF"
			else -> "KTC2_TYPE_ARRAY_VALUE"
		}

		private fun typeTest(inTest: KInstanceOf): String {
			val vIds = when (val vTarget = inTest.target) {
				KStringTarget -> listOf("KTC2_TYPE_STRING")
				is KBoxTarget -> listOf("KTC2_TYPE_BOX_${vTarget.prim.name}")
				is KClassTarget -> mConcrete.filter { it.isSubclassOf(vTarget.cls) }.map { typeId(it) }
				is KInterfaceTarget -> {
					// The built-in types implement these library interfaces too.
					val vBuiltIn = when (vTarget.iface.name) {
						"CharSequence" -> listOf("KTC2_TYPE_STRING")
						"Comparable" -> listOf("KTC2_TYPE_STRING") + KPrim.entries.map { "KTC2_TYPE_BOX_${it.name}" }
						else -> emptyList()
					}
					vBuiltIn + mConcrete.filter { it.implements(vTarget.iface) }.map { typeId(it) }
				}
			}
			var vIndex = mState.typeTests.indexOf(vIds)
			if (vIndex < 0) {
				vIndex = mState.typeTests.size
				mState.typeTests += vIds
			}
			return "is_$vIndex(${bare(expr(inTest.operand))})"
		}

		fun zero(inType: KType): String = when (inType) {
			is KPrimType -> if (inType.prim == KPrim.BOOLEAN) "false" else "0"
			is KRefType, KPtrType -> "NULL"
			else -> "((${cType(inType)}){ 0 })"
		}

		private fun expr(inExpr: KExpr): String = when (inExpr) {
			is KConst -> constant(inExpr)
			KUnitValue -> "((void)0)"
			is KZero -> zero(inExpr.type)
			is KNull -> when (inExpr.type) {
				is KOptType -> "((${cType(inExpr.type)}){ false })"
				// A struct local that holds nothing yet (or no longer): all its references are null.
				is KStructType -> zero(inExpr.type)
				else -> "NULL"
			}
			is KStringLit -> "KTC2_STR(${mState.literals.getOrPut(inExpr.text) { "lit_${mState.literals.size}" }})"
			is KRead -> inExpr.local.cName
			is KGlobalRead -> {
				mState.includes += inExpr.global.unit
				inExpr.global.cName
			}
			is KStaticRead -> {
				mState.includes += inExpr.static.unit
				"(&${inExpr.static.cName})"
			}
			is KUnary -> unary(inExpr)
			is KBinary -> binary(inExpr)
			is KRefEquals -> {
				val vOp = if (inExpr.negated) "!=" else "=="
				when {
					inExpr.right is KNull -> "(${expr(inExpr.left)} $vOp NULL)"
					inExpr.left is KNull -> "(${expr(inExpr.right)} $vOp NULL)"
					else -> "((void*)${expr(inExpr.left)} $vOp (void*)${expr(inExpr.right)})"
				}
			}
			is KConvert -> convert(inExpr)
			is KOptSome -> "((${cType(inExpr.type)}){ true, ${bare(expr(inExpr.operand))} })"
			is KOptHas -> "${expr(inExpr.operand)}.has"
			is KOptValue -> "${expr(inExpr.operand)}.v"
			is KSelect -> when {
				(inExpr.whenFalse as? KConst)?.value == false -> "(${expr(inExpr.condition)} && ${expr(inExpr.whenTrue)})"
				(inExpr.whenTrue as? KConst)?.value == true -> "(${expr(inExpr.condition)} || ${expr(inExpr.whenFalse)})"
				else -> "(${expr(inExpr.condition)} ? ${expr(inExpr.whenTrue)} : ${expr(inExpr.whenFalse)})"
			}
			is KFieldRead -> {
				val vSlot = field(inExpr.target, inExpr.field)
				val vType = inExpr.field.type
				when {
					inExpr.field.inlineSize == 0 -> {
						mState.includes += (vType as KClassType).cls.unit
						if (inExpr.needsCopy) "${vType.cls.cName}__clone(&$vSlot)" else "(&$vSlot)"
					}
					inExpr.field.inlineSize > 0 -> "((ktc2_Array*)&$vSlot)"
					else -> vSlot
				}
			}
			is KStructNew -> {
				mState.includes += inExpr.struct.unit
				val vFields = inExpr.struct.fields.zip(inExpr.values).joinToString(", ") { (vField, vValue) -> ".${vField.cName} = ${bare(expr(vValue))}" }
				"(${inExpr.struct.cName}){ ${vFields.ifEmpty { "0" }} }"
			}
			is KRefCast -> {
				need(inExpr.type)
				"((${cType(inExpr.type)})${expr(inExpr.operand)})"
			}
			is KInstanceOf -> when (inExpr.answer) {
				// An `object` is never null, and the C compiler says so when asked.
				true -> if (generateSequence(inExpr.operand) { (it as? KRefCast)?.operand }.last() is KStaticRead) "true" else "(${expr(inExpr.operand)} != NULL)"
				false -> "false"
				null -> typeTest(inExpr)
			}
			is KIndexRead -> element(inExpr.array, inExpr.index, inExpr.type, inExpr.isChecked)
			is KArrayNew -> {
				need(inExpr.type.element)
				val vLength = (inExpr.length as? KConst)?.value as? Int
				if (inExpr.onStack && vLength != null) {
					val vElement = cType(inExpr.type.element)
					val vStorage = "struct { ktc2_Array header; $vElement data[${maxOf(vLength, 1)}]; }"
					"((ktc2_Array*)&($vStorage){ .header = { { KTC2_STACK | 1, ${arrayTypeId(inExpr.type.element)} }, $vLength, sizeof($vElement) } })"
				} else if (inExpr.onStack) {
					val vElement = cType(inExpr.type.element)
					val vStorage = "struct { ktc2_Array header; $vElement data[KTC2_STACK_ARRAY_BYTES / sizeof($vElement)]; }"
					"ktc2_array_local((ktc2_Array*)&($vStorage){ .header = { { 0, 0 }, 0, 0 } }, ${bare(expr(inExpr.length))}, sizeof($vElement), ${arrayTypeId(inExpr.type.element)})"
				} else "ktc2_array_new(${bare(expr(inExpr.length))}, sizeof(${cType(inExpr.type.element)}), ${arrayTypeId(inExpr.type.element)})"
			}
			is KIntrinsic -> {
				mState.cHeaders += inExpr.headers
				inExpr.functions.forEach { mState.includes += it.unit }
				inExpr.trampoline?.let {
					mState.trampolines[it.name] = it
					mState.cHeaders += "<string.h>"
				}
				val vTemplate = inExpr.template
				if (inExpr.name == "ktc2_call_pointer") {
					// The first argument is a C function pointer, called with the others.
					val vTypes = inExpr.arguments.drop(1).joinToString(", ") { cType(it.type) }.ifEmpty { "void" }
					val vPassed = inExpr.arguments.drop(1).joinToString(", ") { bare(expr(it)) }
					"((${cType(inExpr.type)} (*)($vTypes))${expr(inExpr.arguments[0])})($vPassed)"
				} else if (vTemplate == null) {
					"${inExpr.name}(${arguments(inExpr.arguments)})"
				} else {
					// C text of the program's own: its `$n` are replaced by the arguments.
					val vArguments = inExpr.arguments.map { expr(it) }
					"(" + Regex("\\$(\\d+)").replace(vTemplate) { vMatch -> vArguments[vMatch.groupValues[1].toInt()] } + ")"
				}
			}
			is KStackSlot -> {
				mState.includes += inExpr.cls.unit
				val vPath = generateSequence(inExpr.cls) { it.superClass }.drop(1).joinToString("") { "._super" } + "._header"
				"(&(${inExpr.cls.cName}){ $vPath = { KTC2_STACK | 1, ${typeId(inExpr.cls)} } })"
			}
			is KAlloc -> {
				mState.includes += inExpr.cls.unit
				if (inExpr.onStack) {
					// The object lives in the enclosing block: a compound literal, zeroed each time it is reached.
					val vPath = generateSequence(inExpr.cls) { it.superClass }.drop(1).joinToString("") { "._super" } + "._header"
					"(&(${inExpr.cls.cName}){ $vPath = { KTC2_STACK | 1, ${typeId(inExpr.cls)} } })"
				} else {
					"ktc2_alloc(sizeof(${inExpr.cls.cName}), ${typeId(inExpr.cls)})"
				}
			}
			is KCall -> {
				mState.includes += inExpr.function.unit
				"${inExpr.function.cName}(${arguments(inExpr.arguments)})"
			}
			is KRetain -> retainText(inExpr.type, bare(expr(inExpr.operand)))
		}

		fun constant(inConst: KConst): String = when (val vValue = inConst.value) {
			is Number if inConst.type.prim.isUnsigned -> when (inConst.type.prim) {
				KPrim.UBYTE -> "((uint8_t)${vValue.toInt() and 0xFF})"
				KPrim.USHORT -> "((uint16_t)${vValue.toInt() and 0xFFFF})"
				KPrim.UINT -> "UINT32_C(${vValue.toInt().toUInt()})"
				else -> "UINT64_C(${vValue.toLong().toULong()})"
			}
			is Boolean -> vValue.toString()
			is Char -> "((uint16_t)${vValue.code})"
			is Byte -> "((int8_t)${vValue.toInt()})"
			is Short -> "((int16_t)${vValue.toInt()})"
			is Int -> if (vValue == Int.MIN_VALUE) "INT32_MIN" else if (vValue < 0) "($vValue)" else "$vValue"
			is Long -> if (vValue == Long.MIN_VALUE) "INT64_MIN" else "INT64_C($vValue)"
			is Float -> when {
				vValue.isNaN() -> "NAN"
				vValue.isInfinite() -> if (vValue > 0) "INFINITY" else "(-INFINITY)"
				else -> if (vValue < 0 || 1 / vValue < 0) "(${vValue}f)" else "${vValue}f"
			}
			is Double -> when {
				vValue.isNaN() -> "((double)NAN)"
				vValue.isInfinite() -> if (vValue > 0) "((double)INFINITY)" else "(-(double)INFINITY)"
				else -> if (vValue < 0 || 1 / vValue < 0) "($vValue)" else "$vValue"
			}
			else -> error("unexpected constant ${vValue::class}")
		}

		private fun intPrefix(inPrim: KPrim): String? = when (inPrim) {
			KPrim.INT -> "ktc2_i"
			KPrim.LONG -> "ktc2_l"
			KPrim.UINT -> "ktc2_u"
			KPrim.ULONG -> "ktc2_ul"
			else -> null
		}

		private fun unary(inExpr: KUnary): String {
			val vOperand = expr(inExpr.operand)
			return when (inExpr.op) {
				KUnaryOp.NOT -> "(!$vOperand)"
				KUnaryOp.INV -> "(~$vOperand)"
				KUnaryOp.NEG -> intPrefix(inExpr.type.prim)?.let { "${it}neg(${bare(vOperand)})" } ?: "(-$vOperand)"
			}
		}

		private fun binary(inExpr: KBinary): String {
			val vLeft = expr(inExpr.left)
			val vRight = expr(inExpr.right)
			val vInt = intPrefix(inExpr.operandType)
			fun helper(inName: String) = "$vInt$inName(${bare(vLeft)}, ${bare(vRight)})"
			fun infix(inOp: String) = "($vLeft $inOp $vRight)"
			return when (inExpr.op) {
				KBinaryOp.ADD -> if (vInt != null) helper("add") else infix("+")
				KBinaryOp.SUB -> if (vInt != null) helper("sub") else infix("-")
				KBinaryOp.MUL -> if (vInt != null) helper("mul") else infix("*")
				KBinaryOp.DIV -> when {
					vInt != null -> helper("div")
					// A division by the constant zero is an error for some compilers, even of floating-point
					// numbers, where it is how infinity and NaN are written: a function does it out of their sight.
					((inExpr.right as? KConst)?.value as? Number)?.toDouble() == 0.0 ->
						"((${cType(inExpr.type)})ktc2_divide_by_zero(${bare(vLeft)}, ${bare(vRight)}))"
					else -> infix("/")
				}
				KBinaryOp.REM -> when {
					vInt != null -> helper("rem")
					inExpr.operandType == KPrim.FLOAT -> "fmodf(${bare(vLeft)}, ${bare(vRight)})"
					else -> "fmod(${bare(vLeft)}, ${bare(vRight)})"
				}
				KBinaryOp.SHL -> helper("shl")
				KBinaryOp.SHR -> helper("shr")
				KBinaryOp.USHR -> helper("ushr")
				KBinaryOp.AND -> infix("&")
				KBinaryOp.OR -> infix("|")
				KBinaryOp.XOR -> infix("^")
				KBinaryOp.LT -> infix("<")
				KBinaryOp.LE -> infix("<=")
				KBinaryOp.GT -> infix(">")
				KBinaryOp.GE -> infix(">=")
				KBinaryOp.EQ -> infix("==")
				KBinaryOp.NE -> infix("!=")
				KBinaryOp.CMP -> "KTC2_CMP($vLeft, $vRight)"
			}
		}

		private fun convert(inExpr: KConvert): String {
			val vOperand = expr(inExpr.operand)
			if (inExpr.from.isFloating && !inExpr.to.isFloating) {
				val vHelper = when (inExpr.to) {
					KPrim.LONG -> "ktc2_d2l"
					KPrim.ULONG -> "ktc2_d2ul"
					KPrim.UBYTE, KPrim.USHORT, KPrim.UINT -> "ktc2_d2u"
					else -> "ktc2_d2i"
				}
				val vSaturated = "$vHelper(${bare(vOperand)})"
				val vExact = inExpr.to == KPrim.INT || inExpr.to == KPrim.LONG || inExpr.to == KPrim.UINT || inExpr.to == KPrim.ULONG
				return if (vExact) vSaturated else "((${inExpr.to.cName})$vSaturated)"
			}
			return "((${inExpr.to.cName})$vOperand)"
		}
	}
