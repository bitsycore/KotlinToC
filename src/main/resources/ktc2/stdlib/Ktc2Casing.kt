/** The index of the last range of [inStarts] that starts at or before [inCode]; -1 when none does. */
private fun rangeAt(inStarts: IntArray, inCode: Int): Int {
	var vLow = 0
	var vHigh = inStarts.size - 1
	var vFound = -1
	while (vLow <= vHigh) {
		val vMiddle = (vLow + vHigh) ushr 1
		if (inStarts[vMiddle] <= inCode) {
			vFound = vMiddle
			vLow = vMiddle + 1
		} else {
			vHigh = vMiddle - 1
		}
	}
	return vFound
}

/** Lu, Ll, Lt, Other_Lowercase and Other_Uppercase. */
private fun isCasedCode(inCode: Int): Boolean {
	if (inCode <= 0xFFFF) {
		val vChar = inCode.toChar()
		if (vChar.isUpperCase() || vChar.isLowerCase() || vChar.isTitleCase()) return true
	}
	val vIndex = rangeAt(gCasedStart, inCode)
	if (vIndex >= 0 && inCode <= gCasedEnd[vIndex]) return true
	// Other_Uppercase and Other_Lowercase beyond U+FFFF (PropList.txt), which Kotlin/Native asks of its own tables.
	val vOther = rangeAt(gOtherCasedStart, inCode)
	return vOther >= 0 && inCode <= gOtherCasedEnd[vOther]
}

private val gOtherCasedStart = intArrayOf(0x10780, 0x10783, 0x10787, 0x107b2, 0x1e030, 0x1f130, 0x1f150, 0x1f170)
private val gOtherCasedEnd = intArrayOf(0x10780, 0x10785, 0x107b0, 0x107ba, 0x1e06d, 0x1f149, 0x1f169, 0x1f189)

/** Mn, Me, Cf, Lm, Sk, and Word_Break MidLetter, MidNumLet and Single_Quote. */
private fun isCaseIgnorableCode(inCode: Int): Boolean {
	if (inCode <= 0xFFFF) {
		val vCategory = unicodeCategory(inCode.toChar())
		if (vCategory == kNonSpacingMark || vCategory == kEnclosingMark || vCategory == kFormat || vCategory == kModifierLetter || vCategory == kModifierSymbol) return true
	}
	val vIndex = rangeAt(gCaseIgnorableStart, inCode)
	return vIndex >= 0 && inCode <= gCaseIgnorableEnd[vIndex]
}

/** The code point that ends just before [inIndex] of [inText], and in its upper half how many units it takes. */
private fun codeBefore(inText: String, inIndex: Int): Long {
	val vLow = inText[inIndex - 1]
	if (vLow.isLowSurrogate() && inIndex >= 2 && inText[inIndex - 2].isHighSurrogate()) {
		val vCode = 0x10000 + ((inText[inIndex - 2].code - 0xD800) shl 10) + (vLow.code - 0xDC00)
		return (2L shl 32) or vCode.toLong()
	}
	return (1L shl 32) or vLow.code.toLong()
}

/** The code point that starts at [inIndex] of [inText], and in its upper half how many units it takes. */
private fun codeAt(inText: String, inIndex: Int): Long {
	val vHigh = inText[inIndex]
	if (vHigh.isHighSurrogate() && inIndex + 1 < inText.length && inText[inIndex + 1].isLowSurrogate()) {
		val vCode = 0x10000 + ((vHigh.code - 0xD800) shl 10) + (inText[inIndex + 1].code - 0xDC00)
		return (2L shl 32) or vCode.toLong()
	}
	return (1L shl 32) or vHigh.code.toLong()
}

/** True when the capital sigma at [inIndex] of [inText] is the final one of a word, as Kotlin/Native decides it. */
internal fun isFinalSigmaAt(inText: String, inIndex: Int): Boolean {
	if (inText[inIndex] != '\u03A3' || inIndex == 0) return false
	var vAt = inIndex
	var vCode = 0
	while (vAt > 0) {
		val vBefore = codeBefore(inText, vAt)
		vCode = vBefore.toInt()
		if (!isCaseIgnorableCode(vCode)) break
		vAt -= (vBefore ushr 32).toInt()
	}
	if (vAt == 0 || !isCasedCode(vCode)) return false
	var vNext = inIndex + 1
	while (vNext < inText.length) {
		val vAfter = codeAt(inText, vNext)
		vCode = vAfter.toInt()
		if (!isCaseIgnorableCode(vCode)) return !isCasedCode(vCode)
		vNext += (vAfter ushr 32).toInt()
	}
	return true
}
