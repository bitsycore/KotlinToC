/** Stable merge sort of `[inFrom, inTo)`: equal elements keep their order, as the JVM's sort does. */
private fun <T> mergeSort(inArray: Array<T>, inBuffer: Array<T>, inFrom: Int, inTo: Int, inComparator: Comparator<in T>) {
	if (inTo - inFrom < 2) return
	if (inTo - inFrom <= 8) {
		for (vIndex in inFrom + 1 until inTo) {
			val vValue = inArray[vIndex]
			var vHole = vIndex
			while (vHole > inFrom && inComparator.compare(inArray[vHole - 1], vValue) > 0) {
				inArray[vHole] = inArray[vHole - 1]
				vHole--
			}
			inArray[vHole] = vValue
		}
		return
	}
	val vMiddle = (inFrom + inTo) / 2
	mergeSort(inArray, inBuffer, inFrom, vMiddle, inComparator)
	mergeSort(inArray, inBuffer, vMiddle, inTo, inComparator)
	// Already in order: nothing to merge.
	if (inComparator.compare(inArray[vMiddle], inArray[vMiddle - 1]) >= 0) return
	var vLeft = inFrom
	var vRight = vMiddle
	var vOut = inFrom
	while (vLeft < vMiddle && vRight < inTo) {
		if (inComparator.compare(inArray[vRight], inArray[vLeft]) < 0) inBuffer[vOut++] = inArray[vRight++] else inBuffer[vOut++] = inArray[vLeft++]
	}
	while (vLeft < vMiddle) inBuffer[vOut++] = inArray[vLeft++]
	while (vRight < inTo) inBuffer[vOut++] = inArray[vRight++]
	for (vIndex in inFrom until inTo) inArray[vIndex] = inBuffer[vIndex]
}

public actual fun <T> Array<out T>.sortWith(comparator: Comparator<in T>): Unit {
	if (size > 1) mergeSort(this as Array<T>, newArray<T>(size), 0, size, comparator)
}

public actual fun <T> Array<out T>.sortWith(comparator: Comparator<in T>, fromIndex: Int, toIndex: Int): Unit {
	checkRange(fromIndex, toIndex, size)
	mergeSort(this as Array<T>, newArray<T>(size), fromIndex, toIndex, comparator)
}

public actual fun <T : Comparable<T>> Array<out T>.sort(): Unit {
	if (size > 1) sortWith(naturalOrder())
}

public actual fun <T : Comparable<T>> Array<out T>.sort(fromIndex: Int, toIndex: Int): Unit {
	sortWith(naturalOrder(), fromIndex, toIndex)
}

